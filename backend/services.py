"""Business logic: audio -> transcript -> summary -> report files."""
import logging
import uuid
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path

from flask import current_app

from models import speech_model, summarization_model
from models.speech_model import NoSpeechDetectedError
from models.summarization_model import SummarizationModelError
from utils import audio_processing as ap
from utils import file_utils as fu
from utils import text_utils as tu

logger = logging.getLogger(__name__)


def language_name(code):
    return current_app.config["SUPPORTED_LANGUAGES"].get(code, (code or "unknown").upper())


@contextmanager
def _workspace():
    """Temporary working directory that is always removed afterwards."""
    work = fu.new_temp_dir(current_app.config["UPLOAD_FOLDER"])
    try:
        yield work
    finally:
        fu.cleanup_path(work)


def transcribe_upload(file_storage, safe_name, options):
    """Validate, convert, chunk and transcribe an uploaded audio file."""
    cfg = current_app.config
    with _workspace() as work:
        extension = fu.get_extension(safe_name)
        stored = work / f"upload_{uuid.uuid4().hex}.{extension}"
        file_storage.save(str(stored))

        ap.validate_audio(stored, safe_name, cfg["ALLOWED_AUDIO_EXTENSIONS"], cfg["MAX_CONTENT_LENGTH"])
        wav_path = ap.convert_audio(stored, work)
        duration = ap.get_audio_duration(wav_path)
        chunks = ap.split_audio_into_chunks(wav_path, work / "chunks", cfg["AUDIO_CHUNK_SECONDS"])
        logger.info("Transcribing %.1f s of audio in %d chunk(s)", duration, len(chunks))

        result = speech_model.transcribe_audio_chunks(
            chunks, options["whisper_model"], options["language"], cfg["DEVICE"]
        )

    text = tu.clean_text(result["text"])
    if not text:
        raise NoSpeechDetectedError("No speech was detected in the audio.")
    return {
        "filename": safe_name,
        "duration_seconds": round(duration, 2),
        "duration_text": fu.format_duration(duration),
        "language_code": result["language"],
        "language": language_name(result["language"]),
        "whisper_model": options["whisper_model"],
        "transcript": text,
    }


def analyze_transcript(transcript, summary_length, language_code=None, strict=True):
    """Create the summary plus extracted key points, decisions and action items."""
    cfg = current_app.config
    warnings = []
    summary, summary_error = "", None

    if tu.count_words(transcript) < cfg["SUMMARY_MIN_WORDS"]:
        summary = transcript
        warnings.append("The transcript is very short, so it is shown as the summary without AI rewriting.")
    else:
        try:
            summary = summarization_model.summarize_text(
                transcript, summary_length, cfg["TEXT_CHUNK_WORDS"], cfg["SUMMARIZER_MODEL"], cfg["DEVICE"]
            )
        except SummarizationModelError as exc:
            if strict:
                raise
            summary_error = str(exc)
            warnings.append("The AI summary could not be generated: " + summary_error)

    if language_code and language_code not in ("en", "unknown"):
        warnings.append(
            "The summarisation model and the extraction rules are designed for English. "
            "Results for other languages may be limited."
        )

    return {
        "summary": summary,
        "summary_source": f"AI-generated by {cfg['SUMMARIZER_MODEL']}" if summary and not summary_error else "Unavailable",
        "key_points": tu.extract_key_points(transcript),
        "decisions": tu.extract_decisions(transcript),
        "action_items": tu.extract_action_items(transcript),
        "summary_length": summary_length,
        "warnings": warnings,
    }


def _export_dir():
    path = Path(current_app.config["EXPORT_FOLDER"])
    path.mkdir(parents=True, exist_ok=True)
    return path


def _write_exports(report):
    """Write JSON + TXT exports for a report and return the TXT download names."""
    folder = _export_dir()
    rid = report["id"]
    names = {
        "transcript": f"{rid}_transcript.txt",
        "summary": f"{rid}_summary.txt",
        "report": f"{rid}_report.txt",
    }
    fu.write_text_file(folder / names["transcript"], tu.build_transcript_txt(report))
    fu.write_text_file(folder / names["summary"], tu.build_summary_txt(report))
    fu.write_text_file(folder / names["report"], tu.build_report_txt(report))
    fu.write_json_file(folder / f"{rid}.json", report)
    report["files"] = names
    return names


def save_report(report):
    _write_exports(report)
    fu.write_json_file(_export_dir() / f"{report['id']}.json", report)
    return report


def load_report(report_id):
    """Return a stored report dict or None."""
    if not fu.is_valid_report_id(report_id):
        return None
    path = _export_dir() / f"{report_id}.json"
    if not path.is_file():
        return None
    try:
        return fu.read_json_file(path)
    except (OSError, ValueError):
        return None


def _new_report(meta, analysis):
    report = {
        "id": uuid.uuid4().hex,
        "created_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        **meta,
        **analysis,
    }
    return report


def process_meeting(file_storage, safe_name, options):
    """Full workflow: audio -> transcript -> summary -> action items -> saved report."""
    cfg = current_app.config
    fu.cleanup_old_files(_export_dir(), cfg["EXPORT_RETENTION_HOURS"] * 3600)
    meta = transcribe_upload(file_storage, safe_name, options)
    analysis = analyze_transcript(
        meta["transcript"], options["summary_length"], meta["language_code"], strict=False
    )
    return save_report(_new_report(meta, analysis))


def update_report(report_id, transcript, summary_length):
    """Re-analyse an edited transcript and refresh the stored report/exports."""
    report = load_report(report_id)
    if report is None:
        return None
    analysis = analyze_transcript(transcript, summary_length, report.get("language_code"), strict=True)
    report.update(analysis)
    report["transcript"] = transcript
    return save_report(report)
